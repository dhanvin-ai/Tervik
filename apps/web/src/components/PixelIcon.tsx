export type PixelIconName = keyof typeof BITMAPS;

export function PixelIcon({ name, size = 3 }: { name: PixelIconName; size?: number }) {
  const rows = BITMAPS[name];
  const cells = rows.flatMap((row, y) => [...row].map((pixel, x) => (pixel === '#' ? [x, y] : null)).filter(Boolean) as number[][]);
  return (
    <svg className="lp-pixel-icon" width={11 * size} height={9 * size} viewBox="0 0 11 9" shapeRendering="crispEdges" aria-hidden="true">
      {cells.map(([x, y]) => <rect key={`${x}-${y}`} x={x + 0.08} y={y + 0.08} width={0.84} height={0.84} />)}
    </svg>
  );
}
